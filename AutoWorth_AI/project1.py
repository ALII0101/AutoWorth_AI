def find_col(df, *name_options):
    normalized = {c.lower().replace(" ", "").replace("_", ""): c for c in df.columns}
    for name in name_options:
        key = name.lower().replace(" ", "").replace("_", "")
        if key in normalized:
            return normalized[key]
    return None

